// ─────────────────────────────────────────────
// MERGE with existing vocabulary
// ─────────────────────────────────────────────
const vocabPath = path.join(
  __dirname,
  "..",
  "src",
  "data",
  "vocabulary-generated.ts",
);
const rawContent = fs.readFileSync(vocabPath, "utf8");

// Parse existing entries
const existingMatch = rawContent.match(
  /export const vocabulary = (\[[\s\S]*\]);/,
);
if (!existingMatch) {
  console.error("Could not parse existing vocabulary file");
  process.exit(1);
}
const existing = JSON.parse(existingMatch[1]);
console.log(`Existing entries: ${existing.length}`);

// Use only the YLE entries as the base (in case previous extraction runs
// added garbled SM1/SM2 entries that we want to reset).
const yleBase = existing.filter(
  (e) => e.source === "YLE" || (!e.source && existing.indexOf(e) < 1903),
);
console.log(`YLE base entries: ${yleBase.length}`);

// Add source:"YLE" to all base entries
const existingWithSource = yleBase.map((e) => ({ ...e, source: "YLE" }));

// Build a set of existing Finnish words (lowercase) for dedup
const existingFinnishWords = new Set(
  yleBase.map((e) => e.finnish.toLowerCase().trim()),
);

// Filter new SM1 entries — skip if Finnish word already exists
const sm1New = SM1.filter(
  (e) => !existingFinnishWords.has(e.finnish.toLowerCase().trim()),
).map((e) => ({ ...e, source: "SM1" }));

// Add SM1 to set for SM2 dedup
const combinedFinnishWords = new Set([
  ...existingFinnishWords,
  ...sm1New.map((e) => e.finnish.toLowerCase().trim()),
]);

// Filter new SM2 entries
const sm2New = SM2.filter(
  (e) => !combinedFinnishWords.has(e.finnish.toLowerCase().trim()),
).map((e) => ({ ...e, source: "SM2" }));

console.log(`New SM1 entries: ${sm1New.length}`);
console.log(`New SM2 entries: ${sm2New.length}`);

// Combine all entries
const allEntries = [...existingWithSource, ...sm1New, ...sm2New];

// Reassign sequential IDs
const withIds = allEntries.map((e, i) => ({ id: i + 1, ...e }));

console.log(`Total entries: ${withIds.length}`);

// Generate new file content
const newContent = `// Vocabulary list — YLE Finnish (${existing.length} entries) + Suomen Mestari 1 (${sm1New.length} entries) + Suomen Mestari 2 (${sm2New.length} entries)
// Total: ${withIds.length} entries
// source values: "YLE" | "SM1" | "SM2"

export const vocabulary = ${JSON.stringify(withIds, null, 2)};
`;

fs.writeFileSync(vocabPath, newContent, "utf8");
console.log(
  `\nDone! Wrote ${withIds.length} entries to vocabulary-generated.ts`,
);
